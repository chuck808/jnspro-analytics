"""
AppGatePro Analytics — Documentation Generator
===============================================
Converts markdown chapter files into a TypeScript content module
for the SvelteKit docs route.

Usage:
    python3 scripts/generate-docs.py

Requirements:
    pip install markdown

Workflow:
    1. Edit chapter files in docs/chapters/
    2. Run this script
    3. Commit the updated src/lib/docs/content.ts

Adding a new chapter:
    1. Create docs/chapters/my-chapter.md
    2. Add an entry to CHAPTERS below
    3. Re-run this script
    4. Add a link to Sidebar.svelte if needed

Adding screenshots:
    Use standard markdown image syntax in chapter files:
        ![Alt text](https://your-cdn.com/docs/image.png)

Adding video embeds:
    Use an HTML block directly in the markdown:
        <div class="doc-video">
          <iframe src="https://www.youtube.com/embed/VIDEO_ID"
                  title="Description" allowfullscreen></iframe>
        </div>

    The .doc-video class is styled in [chapter]/+page.svelte prose CSS.
"""

